import fs from 'node:fs/promises';
import { CAMPS } from '../src/features/map/domain/camps.ts';
const read = file => fs.readFile('supabase/modules/'+file,'utf8');
const story = CAMPS.map(c => `update public.peris_camps set tier=${c.tier} where id=${c.id} and not exists(select 1 from public.battles b where b.camp_id=${c.id} and b.status='active') and not exists(select 1 from public.armies a where a.raid_target_id=${c.id} and a.status='moving');`).join('\n');
const rewards = (await read('heroes/battle-rewards.sql')).split('create or replace function public.peris_battle_hero_reward')[1];
const accrual = (await read('campaign/camp-schema.sql')).split('create or replace function public.peris_camp_accrue')[1].split('create or replace function public.peris_deliver_loot')[0];
const sql = `-- Generated by scripts/build-camp-artifact-upgrade.mjs. Existing V16 worlds.
-- Run UPGRADE_TO_V16.sql first on older databases.
-- Preserves accounts, inventories, receipts, camp IDs/positions and farm targets.
-- No table rebuilds. Existing camp stock/defenders are preserved; busy camp metadata is skipped.
begin;
do $$begin if to_regclass('public.peris_camp_stock') is null then raise exception 'Run UPGRADE_TO_V16.sql before this artifact/camp update';end if;end$$;
${await read('heroes/artifact-catalog.sql')}
${await read('map/bandits.sql')}
${story}
create or replace function public.peris_battle_hero_reward${rewards}
create or replace function public.peris_camp_accrue${accrual}
${await read('campaign/peris_start_raid.sql')}
${await read('battle/peris_finish.sql')}
notify pgrst,'reload schema';
commit;
`;
const file = 'supabase/UPDATE_ARTIFACTS_AND_CAMPS.sql';
if (process.argv.includes('--check')) { if ((await fs.readFile(file,'utf8')).replace(/\r\n/g,'\n') !== sql) throw Error('Stale camp/artifact update: run npm run build:camp-artifact-upgrade'); }
else await fs.writeFile(file,sql);
console.log('Focused camp/artifact upgrade '+(process.argv.includes('--check')?'matches':'generated'));
