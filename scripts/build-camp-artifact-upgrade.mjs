import fs from 'node:fs/promises';
import { CAMPS } from '../src/features/map/domain/camps.ts';
const read = async file => (await fs.readFile('supabase/modules/'+file,'utf8')).replace(/\r\n/g,'\n');
const definition=(source,signature)=>{
 const start=source.indexOf('create or replace function public.'+signature),end=source.indexOf('$$;',start)+3;
 if(start<0||end<start)throw Error('Missing SQL definition: '+signature);
 return source.slice(start,end);
};
const story = CAMPS.map(c => `update public.peris_camps set tier=${c.tier} where id=${c.id} and not exists(select 1 from public.battles b where b.camp_id=${c.id} and b.status='active') and not exists(select 1 from public.armies a where a.raid_target_id=${c.id} and a.status='moving');`).join('\n');
const rewards = (await read('heroes/battle-rewards.sql')).split('create or replace function public.peris_battle_hero_reward')[1];
const campSchema=await read('campaign/camp-schema.sql');
const accrual=definition(campSchema,'peris_camp_accrue(');
const economics=[
 'peris_roster_loss_cost(p_initial jsonb,p_survivors jsonb,p_version integer)',
 'peris_roster_loss_cost(p_initial jsonb,p_survivors jsonb)',
 'peris_resource_difference(',
].map(signature=>definition(campSchema,signature)).join('\n');
const legacy=await read('compat/artifact-camp-v16.sql');
const legacyEconomics=[
 'peris_roster_loss_cost(p_initial jsonb,p_survivors jsonb)',
 'peris_resource_difference(',
].map(signature=>definition(legacy,signature)).join('\n');
const legacyBattles=[
 'peris_start_raid(',
 'peris_finish(',
].map(signature=>definition(legacy,signature)).join('\n');
const sql = `-- Generated by scripts/build-camp-artifact-upgrade.mjs. Existing V16 worlds.
-- Run UPGRADE_TO_V16.sql first on older databases.
-- Preserves accounts, inventories, receipts, camp IDs/positions and farm targets.
-- No table rebuilds. Existing camp stock/defenders are preserved; busy camp metadata is skipped.
-- Retains current balance rules and battle finalizers on upgraded worlds.
begin;
do $$begin if to_regclass('public.peris_camp_stock') is null then raise exception 'Run UPGRADE_TO_V16.sql before this artifact/camp update';end if;end$$;
${await read('heroes/artifact-catalog.sql')}
${await read('map/bandits.sql')}
${story}
create or replace function public.peris_battle_hero_reward${rewards}
${accrual}
do $peris_camp_upgrade$
begin
 if exists(select 1 from information_schema.columns where table_schema='public'and table_name='battles'and column_name='balance_version')then
  execute $peris_current$${economics}
revoke all on function public.peris_roster_loss_cost(jsonb,jsonb,integer)from public,anon,authenticated;
$peris_current$;
 else
  execute $peris_legacy_economics$${legacyEconomics}$peris_legacy_economics$;
  -- Pre-balance worlds may already have research and city-raid settlement rules.
  -- Only the original V16 capabilities need the frozen battle replacements.
  if to_regprocedure('public.peris_research_factor(uuid,text)')is null
   and to_regprocedure('public.peris_finish_city_raid(bigint,text,text)')is null then
   execute $peris_legacy_battles$${legacyBattles}$peris_legacy_battles$;
  end if;
 end if;
end $peris_camp_upgrade$;
revoke all on function public.peris_roster_loss_cost(jsonb,jsonb),public.peris_resource_difference(jsonb,jsonb) from public,anon,authenticated;
notify pgrst,'reload schema';
commit;
`;
const file = 'supabase/UPDATE_ARTIFACTS_AND_CAMPS.sql';
if (process.argv.includes('--check')) { if ((await fs.readFile(file,'utf8')).replace(/\r\n/g,'\n') !== sql) throw Error('Stale camp/artifact update: run npm run build:camp-artifact-upgrade'); }
else await fs.writeFile(file,sql);
console.log('Focused camp/artifact upgrade '+(process.argv.includes('--check')?'matches':'generated'));
