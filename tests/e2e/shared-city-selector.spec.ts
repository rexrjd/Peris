import { test, expect } from '@playwright/test';
import { createSolo } from '../../src/features/campaign/domain/newRealm';
import { refreshCityEconomy } from '../../src/features/city/domain/slots';

test('shared city card previews actual cities and retains City and Map selection with keyboard support', async ({ page }, info) => {
    const world = createSolo('Preview'), town = world.settlements[0], errors: string[] = [];
    town.name = 'Willowford';
    world.buildings.forEach(building => building.level = 3);
    world.city_slots = [{ settlement_id: town.id, slot_index: 0, building_type: 'housing', level: 2 }];
    world.settlements.push({ ...town, id: 2, name: 'Frontier beyond the mountains', x: town.x + 1024, y: town.y + 512 });
    world.buildings.push(...world.buildings.map(building => ({ ...building, id: building.id + 100, settlement_id: 2, level: 1 })));
    refreshCityEconomy(world, town.id); refreshCityEconomy(world, 2);
    world.armies[0].start_x = world.armies[0].target_x = town.x;
    world.armies[0].start_y = world.armies[0].target_y = town.y;
    page.on('pageerror', error => errors.push(error.message));
    await page.addInitScript(w => {
        localStorage.setItem('peris-campaign-v6', JSON.stringify(w));
        localStorage.setItem('peris-settings', JSON.stringify({ sound: false, music: false, reducedMotion: true }));
        localStorage.setItem(`peris-welcome:${w.players[0].id}:${w.players[0].created_at}`, 'yes');
    }, world);
    await page.goto('/'); await page.getByRole('button', { name: 'Continue campaign', exact: true }).click();
    await page.getByRole('button', { name: 'City', exact: true }).click();
    await page.getByRole('button', { name: '3D', exact: true }).click();
    const card = page.locator('.city-selector:not(.city-garrison-dock)'), preview = card.locator('.city-selector-preview[data-preview-state]');
    await expect(preview).toHaveAttribute('data-preview-state', 'ready');
    await expect(card).toContainText('Population'); await expect(card).toContainText('Army 186');
    const first = await preview.locator('.city-selector-model').getAttribute('src');
    await page.getByRole('button', { name: 'Current city: Willowford', exact: true }).click();
    await expect(page.getByRole('menu', { name: 'Your cities' })).toBeVisible();
    await page.screenshot({ path: info.outputPath('city-menu.png') });
    await page.keyboard.press('ArrowDown'); await page.keyboard.press('Enter');
    await expect(page.locator('.city-3d-scene.ready')).toHaveAttribute('data-city-seed', /\d+/);
    await expect(card.locator('.city-selector-heading')).toContainText(world.settlements[1].name);
    await expect(preview).toHaveAttribute('data-preview-state', 'ready');
    await expect(card).toContainText('Army 0');
    const second = await preview.locator('.city-selector-model').getAttribute('src'); expect(second).not.toBe(first);
    await page.getByRole('button', { name: 'Map', exact: true }).click();
    await expect(page.locator('.world-map-wrap .city-selector')).toBeVisible();
    await expect(page.getByRole('combobox', { name: 'City territory to manage' })).toHaveCount(0);
    await expect(preview.locator('.city-selector-model')).toHaveAttribute('src', second!);
    const trigger = page.getByRole('button', { name: /^Current city:/ });
    await trigger.focus(); await page.keyboard.press('ArrowDown'); await page.keyboard.press('Escape');
    await expect(trigger).toBeFocused(); await expect(page.getByRole('menu')).toHaveCount(0);
    await trigger.click(); await page.getByRole('menuitemradio', { name: /^Willowford/ }).click();
    await expect(card).toContainText('Army 186');
    await expect(preview.locator('.city-selector-model')).toHaveAttribute('src', first!);
    const bounds = (await card.boundingBox())!, controls = (await page.getByRole('group', {name:'Map view controls'}).boundingBox())!;
    const minimap = (await page.locator('.scene-minimap').boundingBox())!;
    expect(controls.x + controls.width).toBeLessThanOrEqual(minimap.x);
    const header = (await page.locator('.game-header').boundingBox())!;
    expect(bounds.y).toBeGreaterThanOrEqual(header.y + header.height);
    const focus = (await page.getByRole('group', { name: 'Map rotation', exact: true }).boundingBox())!;
    expect(focus.y).toBeGreaterThanOrEqual(bounds.y + bounds.height);
    await trigger.click(); await page.keyboard.press('Tab');
    await expect(page.getByRole('menu', { name: 'Your cities' })).toHaveCount(0);
    await page.getByRole('button', { name: 'Focus your army', exact: true }).click();
    await page.screenshot({ path: info.outputPath('map-card.png') });
    await page.getByRole('button', { name: 'City', exact: true }).click();
    await expect(card.locator('.city-selector-heading')).toContainText('Willowford');
    await page.getByRole('button', { name: 'Open city economy report', exact: true }).click();
    await expect(page.getByRole('dialog')).toBeVisible();
    expect(errors).toEqual([]);
});
