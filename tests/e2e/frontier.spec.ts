test('Frontier 3D landscape selects real camp tiers and preserves drag, zoom and map choice', async ({ page }, testInfo) => {
    test.skip(process.env.FRONTIER_E2E !== '1', 'Requires the isolated Frontier server configuration.');
    const errors: string[] = []; page.on('pageerror', error => errors.push(error.message));
    await page.goto('/?frontier=1');
    await page.getByLabel('Village name').fill('Camp landscape QA');
    await page.getByRole('button', { name: 'Raise your standard' }).click();
    const map = page.locator('.fw-world-map');
    const canvas = map.locator('canvas[aria-label^="Interactive Frontier"]');
    await map.scrollIntoViewIfNeeded();
    await expect(map.locator('.scene-compatibility')).toHaveCount(0);
    await expect(canvas).toBeVisible();
    await expect.poll(() => canvas.evaluate((element: HTMLCanvasElement) => !!element.getContext('webgl2'))).toBe(true);
    // Inspect the displayed frame: between submissions WebGL may legally clear
    // its drawing buffer, even though the compositor retains the visible map.
    await expect.poll(async () => {
        const image = sharp(await canvas.screenshot()), { width = 0, height = 0 } = await image.metadata();
        if (width < 4 || height < 4) return false;
        const pixels = await image.extract({ left: Math.floor((width - 4) / 2), top: Math.floor((height - 4) / 2), width: 4, height: 4 }).removeAlpha().raw().toBuffer();
        return pixels.some(value => value > 0);
    }).toBe(true);
    for (const tier of ['low', 'medium', 'hard']) {
        await page.getByRole('button', { name: new RegExp(`^${tier}$`, 'i') }).click();
        const target = page.locator('.fw-camp-row').first();
        const name = await target.locator('.fw-camp-name strong').innerText();
        await target.click();
        await expect(page.getByRole('dialog')).toContainText(`${tier} difficulty`);
        await page.keyboard.press('Escape');
        await map.scrollIntoViewIfNeeded();
        const marker = map.locator('.scene-label').filter({ hasText: name }).first();
        await expect(marker).toBeVisible();
        await marker.click();
        await expect(page.getByRole('dialog')).toContainText(name);
        await expect(page.getByRole('dialog')).toContainText('Stored resources');
        await expect(page.locator('.battle-3d-canvas')).toHaveCount(0);
        await page.keyboard.press('Escape');
        await map.scrollIntoViewIfNeeded();
        await testInfo.attach(`frontier-3d-${tier}`, { body: await map.screenshot(), contentType: 'image/png' });
    }
    const original = await page.locator('.fw-map-center').innerText();
    // Start on terrain, away from clickable camp labels and map controls.
    const box = (await canvas.boundingBox())!, x = box.x + box.width * .3, y = box.y + box.height * .3;
    await expect.poll(() => canvas.evaluate((element, point) => document.elementFromPoint(point.x, point.y) === element, { x, y })).toBe(true);
    await page.mouse.move(x, y); await page.mouse.down();
    await page.mouse.move(x + 100, y + 40, { steps: 12 }); await page.mouse.up();
    await expect(page.locator('.fw-map-center')).not.toHaveText(original);
    await expect(page.getByRole('dialog')).toHaveCount(0);
    const panned = await page.locator('.fw-map-center').innerText();
    await page.getByRole('combobox', { name: 'Map zoom', exact: true }).selectOption('17');
    await expect(page.locator('.fw-map-center')).toHaveText(panned);
    await canvas.focus(); await page.keyboard.down('ArrowRight');
    await expect(page.locator('.fw-map-center')).not.toHaveText(panned);
    await page.keyboard.up('ArrowRight');
    await page.getByRole('button', { name: 'Classic map', exact: true }).click();
    await expect(page.getByRole('group', { name: 'Frontier camp map', exact: true })).toBeVisible();
    await page.getByRole('button', { name: '3D landscape', exact: true }).click();
    await expect(canvas).toBeVisible();
    await page.getByRole('button', { name: 'My village', exact: true }).click();
    await map.scrollIntoViewIfNeeded();
    await testInfo.attach('frontier-3d-overview', { body: await map.screenshot(), contentType: 'image/png' });
    expect(errors).toEqual([]);
});

